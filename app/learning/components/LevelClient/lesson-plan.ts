/**
 * Flunio lesson v2: a short, predictable core with content-aware practice.
 * The plan is deterministic within a lesson; mistakes get one extra practice
 * round, but do not artificially raise the original assessment score.
 * This module does not read or mutate SRS, XP, progress or theme settings.
 */
import type { ExerciseKind, Word } from "./types";
import type { VerifiedContextKind } from "./verified-content";

export type LessonStep = {
  kind: ExerciseKind;
  wordIndex: number;
  phase: "recognition" | "recall" | "context" | "review";
};

function recallKind(levelId: string, wordIndex: number): ExerciseKind {
  const level = levelId.slice(0, 2).toLowerCase();
  if (level === "a0") return "chooseSlovak";
  if (level === "a1") return wordIndex % 2 === 0 ? "chooseSlovak" : "writeWord";
  return "writeWord";
}

export function buildLessonPlan(
  words: Word[],
  levelId: string,
  contextKinds: readonly VerifiedContextKind[] = []
): LessonStep[] {
  const plan: LessonStep[] = [];

  // Round 1: understand every new word.
  words.forEach((_, wordIndex) => {
    plan.push({ kind: "chooseTranslation", wordIndex, phase: "recognition" });
  });

  // Round 2: recall every word (more demanding on higher levels).
  words.forEach((_, wordIndex) => {
    plan.push({ kind: recallKind(levelId, wordIndex), wordIndex, phase: "recall" });
  });

  // Round 3: use verified sentences, NOT autogenerated "To je <verb>".
  // Spread contexts across the lesson instead of picking only its first words.
  const contexts: LessonStep[] = [];
  words.forEach((_, wordIndex) => {
    const kind = contextKinds[wordIndex];
    if (kind === "buildSentence" || kind === "buildUaSentence") {
      contexts.push({ kind, wordIndex, phase: "context" });
    }
  });

  const maxContexts = Math.min(4, words.length);
  if (contexts.length <= maxContexts) return [...plan, ...contexts];

  for (let i = 0; i < maxContexts; i++) {
    const index = Math.floor(((i + 0.5) * contexts.length) / maxContexts);
    plan.push(contexts[index]);
  }

  return plan;
}

export function buildMistakeReview(
  wordIndices: ReadonlySet<number>,
  words: Word[],
  levelId: string
): LessonStep[] {
  return [...wordIndices]
    .filter((index) => Number.isInteger(index) && index >= 0 && index < words.length)
    .sort((a, b) => a - b)
    .map((wordIndex) => ({
      wordIndex,
      // Easier correction on introductory levels; active recall later.
      kind: recallKind(levelId, wordIndex),
      phase: "review" as const,
    }));
}

export const LESSON_MASTERY_PERCENT = 80;
