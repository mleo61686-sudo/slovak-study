function localeFor(lang: ProfileLang) {
  if (lang === "ua") return "uk";
  return lang;
}

export function isCountryCode(value: unknown): value is CountryCode {
  return typeof value === "string" && COUNTRY_CODE_SET.has(value.toUpperCase());
}

export function normalizeCountryCode(value: unknown): CountryCode | null {
  if (typeof value !== "string") return null;

  const trimmed = value.trim();
  if (!trimmed) return null;

  const upper = trimmed.toUpperCase();
  if (COUNTRY_CODE_SET.has(upper)) return upper as CountryCode;

  return LEGACY_COUNTRY_ALIASES[trimmed.toLocaleLowerCase()] ?? null;
}

export function countryFlag(code: CountryCode | string) {
  const normalized = String(code || "").toUpperCase();
  if (!COUNTRY_CODE_SET.has(normalized)) return "🌍";

  return normalized
    .split("")
    .map((char) => String.fromCodePoint(127397 + char.charCodeAt(0)))
    .join("");
}

export function getCountryName(code: CountryCode | string, lang: ProfileLang) {
  const normalized = String(code || "").toUpperCase();
  if (!COUNTRY_CODE_SET.has(normalized)) return normalized || "";

  try {
    const names = new Intl.DisplayNames([localeFor(lang)], { type: "region" });
    return names.of(normalized) || normalized;
  } catch {
    return normalized;
  }
}

export function getCountryOptions(lang: ProfileLang) {
  return COUNTRY_CODES
    .map((code) => ({
      code,
      flag: countryFlag(code),
      name: getCountryName(code, lang),
    }))
    .sort((a, b) => a.name.localeCompare(b.name, localeFor(lang)));
}
